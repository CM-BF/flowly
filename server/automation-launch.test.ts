import { afterEach, expect, test } from "vitest";
import { mkdtemp, readdir, rm, stat, unlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { AutomationLaunches } from "./automation-launch";
import { emptyBoard } from "../shared/model";
const roots: string[] = [];
afterEach(async () => { await Promise.all(roots.splice(0).map((r) => rm(r, { recursive: true, force: true }))); });
test("private payload survives a pending launch, is scoped and is removed after consumption/deletion", async () => {
  const root = await mkdtemp(join(tmpdir(), "flowly-launch-")); roots.push(root);
  const store = new AutomationLaunches(root);
  const launch = { operationId: "one", model: { provider: "codex", model: "test", modeId: "full-access" }, clientMessageId: "stable", images: [{ mimeType: "image/png" as const, data: "aW1hZ2U=" }] };
  const key = await store.save("task", launch);
  expect((await stat(join(root, "automation-launches", `${key}.json`))).mode & 0o777).toBe(0o600);
  expect(await store.read("task", key)).toEqual(launch);
  await expect(store.read("another", key)).rejects.toThrow("belong");
  const board = emptyBoard();
  board.automation.push({ taskId: "task", projectId: "p", state: "queued", role: "implementer", generation: 1, nudges: 0, failures: 0, reviewRounds: 0, queuedAt: "now", updatedAt: "now", launchKey: key });
  await store.collect(board);
  expect(await store.read("task", key)).toEqual(launch);
  board.automation[0].launchConsumed = true;
  await store.collect(board);
  expect(await readdir(join(root, "automation-launches"))).toEqual([]);
  await expect(store.read("task", key)).rejects.toThrow();
  await store.save("task", launch);
  board.automation = [];
  await store.collect(board);
  expect(await readdir(join(root, "automation-launches"))).toEqual([]);
});
